/**
 * ┌─────────────────────────────────────────────────────────────────────┐
 * │ FILE: src/i18n/translations.js                                      │
 * │                                                                     │
 * │ WHAT THIS FILE IS                                                   │
 * │   Every piece of user-facing text, in English and Hindi.             │
 * │                                                                     │
 * │ WHY THERE IS NO i18n LIBRARY                                         │
 * │   Two languages, no plural rules beyond one/many, no gendered        │
 * │   agreement to resolve, no lazy-loaded locale bundles. i18next is    │
 * │   ~40kB for a lookup in an object, on an app whose whole point is    │
 * │   loading fast on a cheap Android over hotel wifi.                   │
 * │                                                                     │
 * │ ── THE REGISTER: DEVANAGARI, NOT PURE HINDI ─────────────────────────│
 * │   Operators say "टोकन", "कार", "पार्किंग", "गेस्ट" — those ARE the      │
 * │   Hindi words in this trade. Translating them to "प्रतीक-चिन्ह" or    │
 * │   "अतिथि" would be more correct and less readable, which is the      │
 * │   wrong trade on a screen somebody uses two hundred times a shift.   │
 * │   So: Devanagari script, working vocabulary.                         │
 * │                                                                     │
 * │ ── WHAT IS NEVER TRANSLATED ─────────────────────────────────────────│
 * │   Token numbers, car numbers, phone numbers and parking place names. │
 * │   The first three are read aloud to guests and typed back in; the    │
 * │   last is DATA the admin typed, not UI. Digits stay Western — an     │
 * │   operator matching a stub against a screen must see the same        │
 * │   glyphs on both, and every number plate in India is Western digits. │
 * │                                                                     │
 * │ KEYS ARE DOTTED AND GROUPED BY SCREEN                                │
 * │   `checkin.guestName`, not `guestName`. A flat namespace collides    │
 * │   the moment two screens both need "Name", and the collision shows   │
 * │   up as the wrong word on one of them rather than as an error.       │
 * │                                                                     │
 * │ USED BY                                                             │
 * │   src/i18n/index.jsx — the provider and the t() hook                 │
 * └─────────────────────────────────────────────────────────────────────┘
 */

